export const getTrip = (slug: string) => TRIPS.find((t) => t.slug === slug);

export const tripsByRegion = (region: Region) =>
  TRIPS.filter((t) => t.region === region && t.categories.includes("trekking"));

export const tripsByCategory = (category: Category, country: Country = "nepal") =>
  TRIPS.filter((t) => t.country === country && t.categories.includes(category));

export const tripsByCountry = (country: Country) => TRIPS.filter((t) => t.country === country);

export const relatedTrips = (trip: Trip, n = 3) =>
  TRIPS.filter(
    (t) =>
      t.slug !== trip.slug &&
      (t.region === trip.region || t.categories.some((c) => trip.categories.includes(c))),
  ).slice(0, n);

export const categoryLabel = (c: Category) => CATEGORIES.find((x) => x.id === c)?.label ?? c;
export const regionLabel = (r: Region) => REGIONS.find((x) => x.id === r)?.label ?? r;
export const countryLabel = (c: Country) => COUNTRIES.find((x) => x.id === c)?.label ?? c;
